function isSupportedLocale(value) {
  return typeof value === 'string' && SUPPORTED_LOCALES.includes(value);
}

function readStoredLocale() {
  try {
    const value = globalThis.localStorage?.getItem(STORAGE_KEY);
    return isSupportedLocale(value) ? value : DEFAULT_LOCALE;
  } catch {
    return DEFAULT_LOCALE;
  }
}

let currentLocale = readStoredLocale();
const listeners = new Set();

export function getLocale() {
  return currentLocale;
}

export function translate(key, variables = {}) {
  const localeValues = DICTIONARY[currentLocale] ?? DICTIONARY[DEFAULT_LOCALE];
  const fallbackValues = DICTIONARY[DEFAULT_LOCALE];
  const template = localeValues[key] ?? fallbackValues[key] ?? key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/gu, (match, name) => (
    Object.hasOwn(variables, name) ? String(variables[name]) : match
  ));
}

export const t = translate;

function applyAttribute(node, attribute, target) {
  const key = node.getAttribute?.(attribute);
  if (key === null || key === undefined || key === '') return;
  target(key);
}

export function applyTranslations(root = globalThis.document) {
  if (root === undefined || root === null) return;
  const nodes = [];
  if (root.matches?.('[data-i18n], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria-label]')) {
    nodes.push(root);
  }
  nodes.push(...(root.querySelectorAll?.('[data-i18n], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria-label]') ?? []));
  for (const node of nodes) {
    applyAttribute(node, 'data-i18n', (key) => { node.textContent = translate(key); });
    applyAttribute(node, 'data-i18n-placeholder', (key) => { node.placeholder = translate(key); });
    applyAttribute(node, 'data-i18n-title', (key) => { node.title = translate(key); });
    applyAttribute(node, 'data-i18n-aria-label', (key) => { node.setAttribute('aria-label', translate(key)); });
  }
  if (root.documentElement !== undefined) root.documentElement.lang = currentLocale;
}

export function setLocale(locale) {
  if (!isSupportedLocale(locale)) return currentLocale;
  if (locale === currentLocale) {
    applyTranslations();
    return currentLocale;
  }
  currentLocale = locale;
  try {
    globalThis.localStorage?.setItem(STORAGE_KEY, locale);
  } catch {
    // Local storage can be unavailable in private browsing or tests.
  }
  applyTranslations();
  for (const listener of listeners) listener(currentLocale);
  if (typeof globalThis.CustomEvent === 'function' && globalThis.document?.dispatchEvent) {
    globalThis.document.dispatchEvent(new CustomEvent('takt:locale-change', { detail: { locale } }));
  }
  return currentLocale;
}

export function subscribeLocaleChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function localeLabel(locale = currentLocale) {
  return locale === 'en' ? translate('app.languageEnglish') : translate('app.languageJapanese');
}
