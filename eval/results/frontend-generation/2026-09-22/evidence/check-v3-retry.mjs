import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('http://127.0.0.1:4183');
const region = page.locator('section[aria-labelledby="team-heading"]');
await region.locator('textarea').fill('失敗した本文A');
await region.locator('.fail-toggle').click();
await region.locator('.send-button').click();
await region.locator('.delivery-status--failure').waitFor();
await region.locator('textarea').fill('新しい本文B');
const before = await region.locator('.delivery-status').innerText();
await region.getByRole('button', { name: 'この本文を再試行する' }).click();
await region.locator('.delivery-status--success').waitFor();
const after = await region.locator('.sent-body').innerText();
const result = { before, after, observation: '再試行ボタンの上には失敗した本文Aが表示されるが、送信されるのは現在の入力B。共通9項目とは別の追加観察。' };
await writeFile(process.argv[2] ?? '/tmp/independent-regions-v3-retry.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
await browser.close();
